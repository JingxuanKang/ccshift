#!/usr/bin/env bash
# ccshift installer — wires the shift bar into Claude Code's statusline and the
# click handler into tmux. Idempotent: re-run after `git pull` or after moving
# the repo. `./install.sh --uninstall` reverts everything.
#
# What it touches:
#   ~/.claude/settings.json        statusLine.command -> generated wrapper
#   ~/.claude/ccshift-statusline.sh   generated wrapper (previous statusline
#                                     is preserved inside it and runs first)
#   ~/.tmux.conf                   one marked block with the click binding
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CLAUDE_DIR="${CLAUDE_CONFIG_DIR:-$HOME/.claude}"
SETTINGS="$CLAUDE_DIR/settings.json"
WRAPPER="$CLAUDE_DIR/ccshift-statusline.sh"
TMUX_CONF="$HOME/.tmux.conf"
BEGIN_MARK="# >>> ccshift >>>"
END_MARK="# <<< ccshift <<<"

need() { command -v "$1" >/dev/null 2>&1 || { echo "error: $1 is required" >&2; exit 1; }; }
need python3

settings_get_command() {
  python3 - "$SETTINGS" <<'PY'
import json, sys, os
path = sys.argv[1]
try:
    with open(path) as f:
        data = json.load(f)
except (OSError, json.JSONDecodeError):
    data = {}
sl = data.get("statusLine") or {}
print(sl.get("command", ""))
PY
}

settings_set_command() {
  python3 - "$SETTINGS" "$1" <<'PY'
import json, sys, os
path, cmd = sys.argv[1], sys.argv[2]
try:
    with open(path) as f:
        data = json.load(f)
except (OSError, json.JSONDecodeError):
    data = {}
if cmd:
    data["statusLine"] = {"type": "command", "command": cmd}
else:
    data.pop("statusLine", None)
os.makedirs(os.path.dirname(path), exist_ok=True)
with open(path, "w") as f:
    json.dump(data, f, indent=2, ensure_ascii=False)
    f.write("\n")
PY
}

tmux_block() {
  cat <<EOF
$BEGIN_MARK
# ccshift: click the statusline shift bar to switch model/effort for the
# current session. All other clicks pass through untouched.
set -g mouse on
bind-key -n MouseDown1Pane if-shell -F '#{m/r:⇧.*OPUS.*XHIGH,#{mouse_line}}' \\
  'run-shell -b "$ROOT/bin/hud-click.sh #{socket_path} #{pane_id} #{mouse_x} #{mouse_y}"' \\
  'select-pane -t = ; send-keys -M'
$END_MARK
EOF
}

remove_tmux_block() {
  [ -f "$TMUX_CONF" ] || return 0
  python3 - "$TMUX_CONF" "$BEGIN_MARK" "$END_MARK" <<'PY'
import sys
path, begin, end = sys.argv[1], sys.argv[2], sys.argv[3]
with open(path) as f:
    lines = f.readlines()
out, skip = [], False
for line in lines:
    if line.rstrip("\n") == begin:
        skip = True
        continue
    if line.rstrip("\n") == end:
        skip = False
        continue
    if not skip:
        out.append(line)
# drop a trailing blank line left behind by the removed block
while out and out[-1].strip() == "" and len(out) >= 2 and out[-2].strip() == "":
    out.pop()
with open(path, "w") as f:
    f.writelines(out)
PY
}

reload_tmux() {
  command -v tmux >/dev/null 2>&1 || return 0
  if tmux ls >/dev/null 2>&1; then
    tmux source-file "$TMUX_CONF" 2>/dev/null \
      && echo "  reloaded running tmux server" \
      || echo "  note: could not reload tmux config automatically — run: tmux source-file ~/.tmux.conf"
  fi
}

uninstall() {
  # 1. Restore the previous statusline command from the wrapper's marker
  if [ -f "$WRAPPER" ]; then
    prev=$(sed -n 's/^# ccshift-original-command: //p' "$WRAPPER" | head -1)
    current=$(settings_get_command)
    if [ "$current" = "bash $WRAPPER" ]; then
      settings_set_command "$prev"
      echo "restored statusLine.command"
    fi
    rm -f "$WRAPPER"
    echo "removed $WRAPPER"
  fi
  # 2. Remove the tmux block
  remove_tmux_block
  echo "removed ccshift block from $TMUX_CONF"
  reload_tmux
  rm -f "$HOME/.cache/ccshift.lock"
  echo "ccshift uninstalled. The repo itself was not deleted."
}

install() {
  # --- statusline ---
  current=$(settings_get_command)
  if [ "$current" = "bash $WRAPPER" ] && [ -f "$WRAPPER" ]; then
    # Re-install: keep the original command already stored in the wrapper
    prev=$(sed -n 's/^# ccshift-original-command: //p' "$WRAPPER" | head -1)
  else
    prev="$current"
  fi

  {
    echo '#!/usr/bin/env bash'
    echo '# Generated by ccshift install.sh — re-run install.sh instead of editing.'
    echo "# ccshift-original-command: $prev"
    echo 'input=$(cat)'
    if [ -n "$prev" ]; then
      echo '# previous statusline, preserved verbatim:'
      echo "printf '%s' \"\$input\" | { $prev; }"
    fi
    echo "printf '%s' \"\$input\" | bash \"$ROOT/bin/hud-shift-line.sh\""
  } >"$WRAPPER"
  chmod +x "$WRAPPER"

  settings_set_command "bash $WRAPPER"
  if [ -n "$prev" ]; then
    echo "statusline: wrapper installed, previous statusline preserved and runs first"
  else
    echo "statusline: shift bar installed (no previous statusline found)"
  fi

  # --- tmux click layer ---
  if command -v tmux >/dev/null 2>&1; then
    remove_tmux_block   # replace any older block (path may have changed)
    {
      if [ -f "$TMUX_CONF" ] && [ -s "$TMUX_CONF" ]; then echo; fi
      tmux_block
    } >>"$TMUX_CONF"
    echo "tmux: click binding written to $TMUX_CONF"
    reload_tmux
  else
    echo "tmux: not found — the bar will display, but clicking needs tmux >= 3.1"
  fi

  cat <<'EOF'

Done. Open Claude Code inside tmux and the shift bar appears in the statusline:
  ⇧ OPUS  OPUS4.8  FABLE │ LOW  MED  HIGH  XHIGH
Click a token to switch this session's model or effort.
Uninstall anytime with: ./install.sh --uninstall
EOF
}

case "${1:-}" in
  --uninstall|uninstall) uninstall ;;
  ""|--install|install)  install ;;
  *) echo "usage: $0 [--uninstall]" >&2; exit 1 ;;
esac
